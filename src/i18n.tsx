import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useMemo,
  useState,
  type ReactNode,
} from "react";
import { uiTranslations } from "./uiTranslations";
import { effectTranslations } from "./effectTranslations";
import { diagnosticTranslations } from "./diagnosticTranslations";

export type UiLanguage = "zh-CN" | "en" | "ja";
export type TranslationParams = Record<string, string | number>;
export const UI_LANGUAGE_KEY = "day-lilies:ui-language";
export const UI_LANGUAGES: readonly (readonly [UiLanguage, string])[] = [
  ["zh-CN", "简体中文"],
  ["en", "English"],
  ["ja", "日本語"],
];
const messages: Record<string, readonly [string, string]> = {
  ...uiTranslations,
  ...effectTranslations,
  ...diagnosticTranslations,
};
const normalize = (text: string) => text.replace(/\s+/g, " ").trim();
const interpolate = (text: string, params: TranslationParams) =>
  text.replace(/\{(\w+)\}/g, (match, key: string) =>
    String(params[key] ?? match),
  );
const patterns = Object.entries(messages)
  .filter(([source]) => /\{\w+\}/.test(source))
  .map(([source, translations]) => {
    const keys: string[] = [];
    const escaped = normalize(source)
      .split(/(\{\w+\})/)
      .map((part) => {
        const key = /^\{(\w+)\}$/.exec(part);
        if (key) {
          keys.push(key[1]);
          return "(.*?)";
        }
        return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      })
      .join("");
    return {
      source,
      regex: new RegExp(`^${escaped}$`, "s"),
      keys,
      translations,
    };
  });

function translateMessageParams(
  source: string,
  params: TranslationParams,
  language: UiLanguage,
): TranslationParams {
  // This wrapper is generated by the validator: its second value is another
  // application diagnostic, unlike card names and parser details in other values.
  if (source === "处理 {0}：{1}" && typeof params[1] === "string") {
    return { ...params, 1: translate(params[1], language) };
  }
  return params;
}

/** Translate application UI messages only; card names, text and Lua stay untouched. */
export function translate(
  source: string,
  language: UiLanguage,
  params: TranslationParams = {},
): string {
  if (language === "zh-CN") return interpolate(source, params);
  const normalized = normalize(source);
  const pair = messages[source] ?? messages[normalized];
  const index = language === "ja" ? 1 : 0;
  if (pair)
    return interpolate(
      pair[index],
      translateMessageParams(normalized, params, language),
    );
  // Diagnostics and progress messages originate outside React and contain values.
  // Only complete, known message patterns are eligible; captured values are preserved.
  for (const { source: patternSource, regex, keys, translations } of patterns) {
    const match = regex.exec(source);
    if (match)
      return interpolate(
        translations[index],
        translateMessageParams(
          patternSource,
          Object.fromEntries(keys.map((key, i) => [key, match[i + 1]])),
          language,
        ),
      );
  }
  if (source.includes("\n"))
    return source
      .split("\n")
      .map((line) => translate(line, language, params))
      .join("\n");
  return interpolate(source, params);
}

export function readUiLanguage(storage?: Pick<Storage, "getItem">): UiLanguage {
  try {
    const value = (storage ?? globalThis.localStorage)?.getItem(
      UI_LANGUAGE_KEY,
    );
    return value === "en" || value === "ja" || value === "zh-CN"
      ? value
      : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

type I18nContextValue = {
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
  t: (source: string, params?: TranslationParams) => string;
};
const I18nContext = createContext<I18nContextValue>({
  language: "zh-CN",
  setLanguage: () => {},
  t: (source, params) => translate(source, "zh-CN", params),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<UiLanguage>(readUiLanguage);
  const t = useCallback(
    (source: string, params?: TranslationParams) =>
      translate(source, language, params),
    [language],
  );
  useEffect(() => {
    try {
      localStorage.setItem(UI_LANGUAGE_KEY, language);
    } catch {
      /* Interface still works when browser storage is unavailable. */
    }
    document.documentElement.lang = language;
    document.title = t("萱草工坊 · Day Lilies");
  }, [language, t]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
